export type StoryScene = {
  /**
   * Якорь сцены. Для разделов из NAV_SECTIONS совпадает с их id,
   * поэтому ссылки хедера и футера `/#id` продолжают работать.
   */
  readonly id: string;
  /** Подпись точки в боковом навигаторе. */
  readonly label: string;
  /**
   * Сколько экранов прокрутки занимает сцена.
   * Последняя длиннее на один экран: после неё закрепление снимается.
   */
  readonly weight: number;
};

